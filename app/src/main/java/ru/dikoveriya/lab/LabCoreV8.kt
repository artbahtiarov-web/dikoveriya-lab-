package ru.dikoveriya.lab

import android.database.sqlite.SQLiteDatabase

/**
 * Additive schema evolution for the laboratory source of truth.
 * Old events, assessments, measurements, operations and recipe rows are never overwritten.
 * All schema upgrades run inside SQLiteOpenHelper's upgrade transaction.
 */
internal object LabCoreV8 {
    fun create(db: SQLiteDatabase) {
        db.execSQL("""CREATE TABLE IF NOT EXISTS culture_audit (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            culture_id INTEGER NOT NULL REFERENCES cultures(id),
            recorded_at INTEGER NOT NULL,
            source TEXT NOT NULL,
            operation_id TEXT REFERENCES lab_operations(id),
            before_qty INTEGER, after_qty INTEGER,
            before_kind TEXT, after_kind TEXT,
            before_status TEXT, after_status TEXT,
            before_batch_id INTEGER, after_batch_id INTEGER,
            before_recipe_id INTEGER, after_recipe_id INTEGER,
            before_stage TEXT, after_stage TEXT,
            before_location TEXT, after_location TEXT
        )""".trimIndent())
        db.execSQL("CREATE INDEX IF NOT EXISTS idx_culture_audit ON culture_audit(culture_id,recorded_at,id)")
        db.execSQL("""CREATE TRIGGER IF NOT EXISTS trg_culture_audit_update
            AFTER UPDATE OF quantity,status,quantity_kind,medium_batch_id,medium_recipe_id,stage,location ON cultures
            WHEN OLD.quantity IS NOT NEW.quantity OR OLD.status IS NOT NEW.status
              OR OLD.quantity_kind IS NOT NEW.quantity_kind
              OR OLD.medium_batch_id IS NOT NEW.medium_batch_id
              OR OLD.medium_recipe_id IS NOT NEW.medium_recipe_id
              OR OLD.stage IS NOT NEW.stage OR OLD.location IS NOT NEW.location
            BEGIN
                INSERT INTO culture_audit (
                    culture_id,recorded_at,source,before_qty,after_qty,before_kind,after_kind,
                    before_status,after_status,before_batch_id,after_batch_id,
                    before_recipe_id,after_recipe_id,before_stage,after_stage,before_location,after_location
                ) VALUES (
                    NEW.id,CAST(strftime('%s','now') AS INTEGER)*1000,'Изменение',
                    OLD.quantity,NEW.quantity,OLD.quantity_kind,NEW.quantity_kind,
                    OLD.status,NEW.status,OLD.medium_batch_id,NEW.medium_batch_id,
                    OLD.medium_recipe_id,NEW.medium_recipe_id,OLD.stage,NEW.stage,OLD.location,NEW.location
                );
            END""".trimIndent())
    }

    fun migrateFrom7(db: SQLiteDatabase) {
        val hasRecordKind=db.rawQuery("PRAGMA table_info(culture_measurements)",null).use { c ->
            var found=false
            while(c.moveToNext()) if(c.getString(1)=="record_kind")found=true
            found
        }
        if(!hasRecordKind) db.execSQL("ALTER TABLE culture_measurements ADD COLUMN record_kind TEXT NOT NULL DEFAULT 'observation'")
        // Historic baseline marker was generated by the app, not a user-facing free-text heuristic.
        db.execSQL("UPDATE culture_measurements SET record_kind='baseline' WHERE notes='Показатели при создании'")
        create(db)
        seedCurrentState(db,"Состояние до миграции")
    }

    /** Old backups do not contain historical audit snapshots: mark what is known, never invent a past state. */
    fun seedCurrentState(db: SQLiteDatabase, source: String) {
        db.execSQL("""INSERT INTO culture_audit(culture_id,recorded_at,source,after_qty,after_kind,
            after_status,after_batch_id,after_recipe_id,after_stage,after_location)
            SELECT id,CAST(strftime('%s','now') AS INTEGER)*1000,?,quantity,quantity_kind,
                   status,medium_batch_id,medium_recipe_id,stage,location FROM cultures""".trimIndent(),arrayOf(source))
    }

    fun validate(db: SQLiteDatabase) {
        db.rawQuery("PRAGMA foreign_key_check",null).use { cursor ->
            require(!cursor.moveToFirst()) { "Нарушены ссылки SQLite" }
        }
        db.rawQuery("PRAGMA integrity_check",null).use { cursor ->
            require(cursor.moveToFirst() && cursor.getString(0)=="ok") { "Проверка целостности SQLite не пройдена" }
        }
    }
}
